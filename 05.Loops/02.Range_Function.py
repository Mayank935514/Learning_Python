## The python range() function returns a sequence of numbers, in a given range

# Example-1
r=range(5)
print(r)
l=list(r)
print(l)

# Example-2
r=range(10,20)
l=list(r)
print(l)

# Example-3
r=range(5)
print(type(r))

# Example-4
r=range(10,20,2)
l=list(r)
print(l)

# Example-5
r=range(20,10,-2)
l=list(r)
print(l)
